import json
from pathlib import Path

from fastapi import APIRouter
from pydantic import BaseModel

router = APIRouter(prefix="/api/design", tags=["design"])

BASE_DIR = Path(__file__).resolve().parent.parent.parent
TOKENS_JSON_PATH = BASE_DIR / "data" / "design_tokens.json"
TOKENS_CSS_PATH = BASE_DIR / "public" / "design-tokens.css"

_APP_TOKEN_DEFAULTS = {
    "--font-display": '-apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif',
    "--font-body": '-apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif',
    "--font-mono": "ui-monospace, SFMono-Regular, Menlo, Consolas, monospace",
    "--c-ink": "#1a1a1a",
    "--c-slate": "#6b6b6b",
    "--c-bg-1": "#fafafa",
    "--c-accent": "#1a1a1a",
    "--c-accent-contrast": "#ffffff",
    "--line-strength": "12%",
    "--radius": "6px",
    "--label-tracking": "0.02em",
}


class DesignTokens(BaseModel):
    tokens: dict[str, str] = {}
    motionEnabled: bool = True
    density: int = 3
    ctaStyle: str = "filled"


@router.get("/tokens")
def get_tokens() -> DesignTokens | None:
    if not TOKENS_JSON_PATH.exists():
        return None
    return DesignTokens(**json.loads(TOKENS_JSON_PATH.read_text(encoding="utf-8")))


@router.post("/tokens")
def save_tokens(payload: DesignTokens) -> dict:
    TOKENS_JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    TOKENS_JSON_PATH.write_text(payload.model_dump_json(indent=2), encoding="utf-8")

    merged = {**_APP_TOKEN_DEFAULTS, **payload.tokens}
    ink = merged["--c-ink"]
    line_strength = merged["--line-strength"]
    radius = merged.get("--radius", "6px")
    try:
        radius_px = float(str(radius).rstrip("px"))
    except ValueError:
        radius_px = 6.0

    css_vars = {
        "--bg": merged["--c-bg-1"],
        "--surface": "#ffffff",
        "--text": ink,
        "--text-muted": merged["--c-slate"],
        "--accent": merged["--c-accent"],
        "--accent-contrast": merged["--c-accent-contrast"],
        "--border": f"color-mix(in srgb, {ink} {line_strength}, white)",
        "--chip-bg": f"color-mix(in srgb, {ink} 6%, white)",
        "--font-display": merged["--font-display"],
        "--font-body": merged["--font-body"],
        "--font-mono": merged["--font-mono"],
        "--radius-sm": f"{radius_px:g}px",
        "--radius-lg": f"{radius_px + 4:g}px",
        "--label-tracking": merged["--label-tracking"],
    }

    lines = [
        "/* Generated by the landing/hud/v5-scan design tweak panel -- do not hand-edit,",
        "   it is overwritten every time \"Save & Implement\" is clicked. */",
        "/* This design direction is light-themed. --surface/--chip-bg are set",
        "   explicitly (not just --bg/--text) so a browser in dark mode doesn't end up",
        "   with style.css's dark --surface under this file's light --text (unreadable).",
        "   color-scheme:light only affects native form-control theming, nothing else. */",
        ":root {",
        "  color-scheme: light;",
    ]
    lines += [f"  {k}: {v};" for k, v in css_vars.items()]
    lines.append("}")
    TOKENS_CSS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")

    return {"status": "saved", "css_path": "/design-tokens.css"}
